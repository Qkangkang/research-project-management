-- =============================================================================
-- 科研项目管理系统 — Flowable 7.2.0 Schema 对齐
-- 版本：V09
-- 背景：
--   1. 技术文档锁定 Flowable 7.x（Batch-6 经人工确认锁定 7.2.0）；
--   2. V03 是手工整理的 Flowable 建表脚本（评审 #6），经与 flowable-engine 7.2.0
--      官方脚本（org/flowable/db/create/flowable.postgres.create.engine.sql /
--      .history.sql、flowable-engine-common 的 .common.sql、flowable-idm-engine 的
--      .identity.sql）逐表 diff，发现缺 18 张表、7 张共享表缺列，且未写入
--      schema.version 等引擎元数据；
--   3. 应用配置 database-schema-update=false（禁止引擎启动自动建表/改表），
--      引擎启动时校验 ACT_GE_PROPERTY.schema.version；缺失会导致启动失败。
-- 处理原则：
--   - 不修改历史脚本 V03（Flyway 迁移不可变）；
--   - 仅补齐 7.2.0 官方脚本要求的表/列/索引/版本元数据；
--   - 全部语句幂等（IF NOT EXISTS / ON CONFLICT DO NOTHING），可安全重复执行；
--   - 不创建外键（与 V03 一致，Flowable 不依赖 FK 语义）；
--   - 升级 Flowable 版本必须新增后续迁移脚本，禁止改动本脚本。
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS flowable;

SET search_path TO flowable, public;

-- -----------------------------------------------------------------------------
-- 1. 表名对齐：7.2.0 官方表名为 ACT_RU_EXTERNAL_JOB
--    V03 误用 ACT_RU_EXTERNAL_WORKER_JOB；两表列定义完全一致，重命名保留数据。
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'flowable' AND table_name = 'act_ru_external_worker_job')
       AND NOT EXISTS (SELECT 1 FROM information_schema.tables
                       WHERE table_schema = 'flowable' AND table_name = 'act_ru_external_job') THEN
        ALTER TABLE flowable.ACT_RU_EXTERNAL_WORKER_JOB RENAME TO ACT_RU_EXTERNAL_JOB;
    END IF;
END $$;

